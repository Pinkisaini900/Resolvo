def perform_action(topic, urgency, sentiment, customer_context):

    article = knowledge_base.get(topic)

    if article is None:
        return {
            "action": "Create general support ticket",
            "escalation": True,
            "reason": "No matching knowledge article found."
        }

    action = article["action"]
    escalation = article["escalation"]
    reason = "Policy-based action selected."

    # Escalate high-risk cases
    if urgency == "High":
        escalation = True
        reason = "High urgency detected."

    if sentiment == "Negative" and urgency == "High":
        escalation = True
        reason = "High urgency + negative customer sentiment."

    # Previous repeated issues
    if customer_context.get("previous_tickets", 0) >= 3:
        escalation = True
        reason = "Customer has multiple previous support tickets."

    return {
        "action": action,
        "escalation": escalation,
        "reason": reason
    }


