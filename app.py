support_sessions = {}


def customer_support_agent(customer_id, message):

    # ---------------------------------------
    # STEP 1 — Customer Context
    # ---------------------------------------

    customer_context = get_customer_context(customer_id)

    if not customer_context["found"]:
        return {
            "status": "ERROR",
            "message": "Customer ID not found."
        }

    # ---------------------------------------
    # STEP 2 — Analyze Message
    # ---------------------------------------

    analysis = analyze_message(message)

    # ---------------------------------------
    # STEP 3 — Knowledge Reasoning
    # ---------------------------------------

    topic = analysis["topic"]
    article = knowledge_base.get(topic)

    # ---------------------------------------
    # STEP 4 — Autonomous Action
    # ---------------------------------------

    action_result = perform_action(
        topic,
        analysis["urgency"],
        analysis["sentiment"],
        customer_context
    )

    # ---------------------------------------
    # STEP 5 — Ticket ID
    # ---------------------------------------

    ticket_id = "TKT-" + str(uuid.uuid4())[:8].upper()

    # ---------------------------------------
    # STEP 6 — Response Generation
    # ---------------------------------------

    if action_result["escalation"]:
        status = "ESCALATED"

        response = (
            f"Hello {customer_context['name']}, "
            f"I understand your {analysis['intent'].lower()} issue. "
            f"I have investigated your request and initiated: "
            f"{action_result['action']}. "
            f"Because this case requires additional attention, "
            f"I have escalated it to a human support agent. "
            f"Your ticket ID is {ticket_id}."
        )
    else:
        status = "RESOLVED"

        response = (
            f"Hello {customer_context['name']}, "
            f"I have identified your issue as a {analysis['intent'].lower()} request. "
            f"Based on our support policy, I have initiated: "
            f"{action_result['action']}. "
            f"Your ticket ID is {ticket_id}."
        )

    # ---------------------------------------
    # STEP 7 — Complete Human Handoff Context
    # ---------------------------------------

    handoff_context = {
        "ticket_id": ticket_id,
        "customer_id": customer_id,
        "customer_name": customer_context["name"],
        "customer_plan": customer_context["plan"],
        "customer_history": customer_context["previous_issues"],
        "customer_message": message,
        "detected_intent": analysis["intent"],
        "sentiment": analysis["sentiment"],
        "urgency": analysis["urgency"],
        "knowledge_topic": topic,
        "policy": article["policy"] if article else "No policy found",
        "action_taken": action_result["action"],
        "escalation_reason": action_result["reason"],
        "status": status
    }

    # ---------------------------------------
    # STEP 8 — Context Retention
    # ---------------------------------------

    if customer_id not in support_sessions:
        support_sessions[customer_id] = []

    support_sessions[customer_id].append({
        "customer_message": message,
        "ticket_id": ticket_id,
        "status": status
    })

    return {
        "status": status,
        "ticket_id": ticket_id,
        "response": response,
        "analysis": analysis,
        "customer_context": customer_context,
        "knowledge": article,
        "action": action_result,
        "handoff_context": handoff_context
    }


