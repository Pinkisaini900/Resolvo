def analyze_message(message):

    text = message.lower()

    # -----------------------------
    # INTENT DETECTION
    # -----------------------------

    if any(word in text for word in [
        "payment", "paid", "payment failed",
        "money deducted", "money cut", "charged"
    ]):
        intent = "Billing"
        topic = "payment_failed"

    elif any(word in text for word in [
        "refund", "return my money", "money back"
    ]):
        intent = "Billing"
        topic = "refund"

    elif any(word in text for word in [
        "delivery", "delivered", "late",
        "delay", "order not received"
    ]):
        intent = "Order"
        topic = "order_delay"

    elif any(word in text for word in [
        "damaged", "broken", "defective"
    ]):
        intent = "Order"
        topic = "damaged_product"

    elif any(word in text for word in [
        "password", "login", "sign in", "account"
    ]):
        intent = "Account"
        topic = "password"

    elif any(word in text for word in [
        "error", "bug", "crash", "not working",
        "technical", "website down", "app not working"
    ]):
        intent = "Technical"
        topic = "technical"

    else:
        intent = "General"
        topic = "technical"

    # -----------------------------
    # SENTIMENT DETECTION
    # -----------------------------

    negative_words = [
        "angry", "frustrated", "worst", "terrible",
        "useless", "hate", "complaint", "disappointed",
        "ridiculous", "bad", "urgent"
    ]

    positive_words = [
        "thanks", "thank you", "good",
        "great", "happy", "excellent"
    ]

    negative_score = sum(word in text for word in negative_words)
    positive_score = sum(word in text for word in positive_words)

    if negative_score > positive_score:
        sentiment = "Negative"
    elif positive_score > negative_score:
        sentiment = "Positive"
    else:
        sentiment = "Neutral"

    # -----------------------------
    # URGENCY DETECTION
    # -----------------------------

    high_urgency_words = [
        "urgent", "immediately", "asap",
        "emergency", "right now", "fraud",
        "money deducted", "account hacked"
    ]

    if any(word in text for word in high_urgency_words):
        urgency = "High"
    elif any(word in text for word in [
        "soon", "delay", "waiting"
    ]):
        urgency = "Medium"
    else:
        urgency = "Low"

    return {
        "intent": intent,
        "topic": topic,
        "sentiment": sentiment,
        "urgency": urgency
    }


