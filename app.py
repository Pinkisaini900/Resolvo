import gradio as gr


def run_support(customer_id, message):

    if not customer_id or not message:
        return (
            "⚠️ Please enter Customer ID and Customer Message.",
            "",
            "",
            "",
            "",
            ""
        )

    result = customer_support_agent(
        customer_id.strip(),
        message.strip()
    )

    if result.get("status") == "ERROR":
        return (
            result["message"],
            "",
            "",
            "",
            "",
            ""
        )

    analysis = result["analysis"]
    action = result["action"]
    customer = result["customer_context"]

    customer_info = (
        f"Name: {customer['name']}\n"
        f"Plan: {customer['plan']}\n"
        f"Location: {customer['location']}\n"
        f"Previous Tickets: {customer['previous_tickets']}\n"
        f"Previous Issues: {', '.join(customer['previous_issues'])}"
    )

    analysis_info = (
        f"Intent: {analysis['intent']}\n"
        f"Urgency: {analysis['urgency']}\n"
        f"Sentiment: {analysis['sentiment']}\n"
        f"Topic: {analysis['topic']}"
    )

    action_info = (
        f"Action Taken: {action['action']}\n"
        f"Escalation: {'YES 🚨' if action['escalation'] else 'NO ✅'}\n"
        f"Reason: {action['reason']}"
    )

    knowledge_info = (
        f"Category: {result['knowledge']['category']}\n\n"
        f"Policy:\n{result['knowledge']['policy']}"
    )

    handoff_info = json.dumps(
        result["handoff_context"],
        indent=2
    )

    return (
        result["response"],
        customer_info,
        analysis_info,
        action_info,
        knowledge_info,
        handoff_info
    )


